data class ChatMessage(val role: String, val content: String)

@Composable
fun ChatAssistantTool() {
    val context = androidx.compose.ui.platform.LocalContext.current
    val prefs = remember { context.getSharedPreferences("wamarketing_persistent_store", android.content.Context.MODE_PRIVATE) }
    val backendUrl = remember { AppConfig.getBackendUrl(prefs) }
    val coroutineScope = rememberCoroutineScope()
    var inputQuery by remember { mutableStateOf("") }
    var isLoading by remember { mutableStateOf(false) }

    var messages by remember {
        mutableStateOf(
            listOf(
                ChatMessage(
                    "assistant",
                    "Welcome to WA Marketing AI Assistant!\n\n" +
                    "I can guide you on WhatsApp Cloud API integration, contact & lead imports (CSV/Excel/PDF), campaign broadcasting, and APK distribution.\n\n" +
                    "Developer: Barkat Ali (https://barkatai.ihsanraza.com/#about)."
                )
            )
        )
    }

    val quickQuestions = listOf(
        "Who is the developer?",
        "How to import Excel/PDF contacts?",
        "Connect WhatsApp Cloud API",
        "How to launch campaigns?",
        "Distribute APK files"
    )

    Column(verticalArrangement = Arrangement.spacedBy(12.dp)) {
        // Quick Chips
        Text("Frequently Asked Topics:", style = MaterialTheme.typography.labelMedium, fontWeight = FontWeight.Bold)
        LazyRow(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            items(quickQuestions) { q ->
                SuggestionChip(
                    onClick = {
                        inputQuery = q
                    },
                    label = { Text(q, style = MaterialTheme.typography.labelSmall) }
                )
            }
        }

        // Messages Box
        Card(
            modifier = Modifier.fillMaxWidth(),
            shape = RoundedCornerShape(16.dp),
            colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.35f)),
            border = CardDefaults.outlinedCardBorder()
        ) {
            Column(
                modifier = Modifier.padding(12.dp),
                verticalArrangement = Arrangement.spacedBy(10.dp)
            ) {
                messages.forEach { msg ->
                    val isUser = msg.role == "user"
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = if (isUser) Arrangement.End else Arrangement.Start
                    ) {
                        Surface(
                            shape = RoundedCornerShape(
                                topStart = 12.dp, topEnd = 12.dp,
                                bottomStart = if (isUser) 12.dp else 2.dp,
                                bottomEnd = if (isUser) 2.dp else 12.dp
                            ),
                            color = if (isUser) WhatsAppGreen else MaterialTheme.colorScheme.surface,
                            border = if (!isUser) CardDefaults.outlinedCardBorder() else null,
                            modifier = Modifier.fillMaxWidth(0.9f)
                        ) {
                            Column(modifier = Modifier.padding(12.dp)) {
                                Text(
                                    text = if (isUser) "You" else "WA Marketing AI",
                                    style = MaterialTheme.typography.labelSmall,
                                    fontWeight = FontWeight.Bold,
                                    color = if (isUser) Color(0xFF00381B) else WhatsAppGreen
                                )
                                Spacer(modifier = Modifier.height(4.dp))
                                Text(
                                    text = msg.content,
                                    style = MaterialTheme.typography.bodyMedium,
                                    color = if (isUser) Color(0xFF00381B) else MaterialTheme.colorScheme.onSurface
                                )
                            }
                        }
                    }
                }

                if (isLoading) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        CircularProgressIndicator(modifier = Modifier.size(16.dp), strokeWidth = 2.dp)
                        Spacer(modifier = Modifier.width(8.dp))
                        Text("AI Assistant is thinking...", style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
                    }
                }
            }
        }

        // Input row
        Row(
            modifier = Modifier.fillMaxWidth(),
            verticalAlignment = Alignment.CenterVertically
        ) {
            OutlinedTextField(
                value = inputQuery,
                onValueChange = { inputQuery = it },
                modifier = Modifier.weight(1f),
                placeholder = { Text("Ask anything about WA Marketing...") },
                singleLine = true,
                shape = RoundedCornerShape(12.dp)
            )
            Spacer(modifier = Modifier.width(8.dp))
            Button(
                onClick = {
                    val prompt = inputQuery.trim()
                    if (prompt.isNotBlank() && !isLoading) {
                        messages = messages + ChatMessage("user", prompt)
                        inputQuery = ""
                        isLoading = true
                        coroutineScope.launch {
                            val reply = withContext(Dispatchers.IO) {
                                try {
                                    val url = URL("$backendUrl/api/v1/ai/chat")
                                    val conn = url.openConnection() as HttpURLConnection
                                    AppConfig.applyStandardHeaders(conn)
                                    conn.requestMethod = "POST"
                                    conn.setRequestProperty("Content-Type", "application/json")
                                    conn.doOutput = true
                                    conn.connectTimeout = 8000
                                    conn.readTimeout = 8000
                                    val payload = JSONObject()
                                    payload.put("message", prompt)
                                    conn.outputStream.use { it.write(payload.toString().toByteArray(Charsets.UTF_8)) }
                                    if (conn.responseCode in 200..299) {
                                        val resp = conn.inputStream.bufferedReader().use { it.readText() }
                                        val json = JSONObject(resp)
                                        json.optString("reply", "")
                                    } else {
                                        null
                                    }
                                } catch (_: Exception) {
                                    null
                                }
                            } ?: run {
                                val lower = prompt.lowercase()
                                if (lower.contains("barkat") || lower.contains("developer") || lower.contains("who made")) {
                                    "WA Marketing was developed by **Barkat Ali**, senior full-stack mobile & cloud engineer.\nPortfolio: https://barkatai.ihsanraza.com/#about"
                                } else if (lower.contains("excel") || lower.contains("pdf") || lower.contains("contact") || lower.contains("import")) {
                                    "To import contacts: Open Contacts -> Import. Pick CSV, Excel (.xlsx/.xls), or PDF. The app validates phone numbers and flags duplicates before importing."
                                } else if (lower.contains("whatsapp") || lower.contains("api") || lower.contains("token")) {
                                    "To connect WhatsApp: Go to Settings -> Connect Number. Enter your Phone Number ID and Access Token, then tap 'Test & Verify with Meta API'."
                                } else if (lower.contains("apk") || lower.contains("media")) {
                                    "To share APK files: Upload your APK from phone storage in Media Library. It generates a 1-click cloud link for instant download via WhatsApp."
                                } else {
                                    "I am here to help you get the most out of WA Marketing! Ask about imports, campaigns, WhatsApp Cloud API, or developer Barkat Ali."
                                }
                            }
                            isLoading = false
                            messages = messages + ChatMessage("assistant", reply)
                        }
                    }
                },
                shape = RoundedCornerShape(12.dp),
                colors = ButtonDefaults.buttonColors(containerColor = WhatsAppGreen),
                enabled = inputQuery.isNotBlank() && !isLoading,
                modifier = Modifier.height(52.dp)
            ) {
                Icon(Icons.Default.Send, contentDescription = "Send", tint = Color(0xFF00381B))
            }
        }
    }
}
